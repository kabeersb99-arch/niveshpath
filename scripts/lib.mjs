// Shared helpers for the data jobs. Node 20+, no dependencies.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const DATA = path.join(ROOT, 'www', 'data');
export const UA = 'NiveshPath-personal-app/0.1 (single-user, non-commercial; polite scheduled fetch)';

export const readJson = async (p) => JSON.parse(await readFile(p, 'utf8'));
export const writeJson = (p, obj) => writeFile(p, JSON.stringify(obj, null, 2) + '\n');

/** Honour robots.txt for our user agent ("*" rules). Returns true when the path is allowed or no robots.txt exists. */
export function robotsAllows(robotsTxt, pathname) {
  let applies = false, allowed = true, best = -1;
  for (const raw of robotsTxt.split(/\r?\n/)) {
    const line = raw.replace(/#.*/, '').trim();
    const m = line.match(/^([A-Za-z-]+)\s*:\s*(.*)$/);
    if (!m) continue;
    const k = m[1].toLowerCase(), v = m[2].trim();
    if (k === 'user-agent') applies = v === '*';
    else if (applies && (k === 'disallow' || k === 'allow') && v) {
      const rule = v.replace(/\*$/, '');
      if (pathname.startsWith(rule) && rule.length > best) { best = rule.length; allowed = k === 'allow'; }
    }
  }
  return allowed;
}

export async function fetchText(url, { timeoutMs = 30000, retries = 2, checkRobots = true } = {}) {
  const u = new URL(url);
  if (checkRobots) {
    try {
      const r = await fetch(u.origin + '/robots.txt', { headers: { 'user-agent': UA }, signal: AbortSignal.timeout(15000) });
      if (r.ok && !robotsAllows(await r.text(), u.pathname)) throw new Error('robots.txt disallows ' + u.pathname);
    } catch (e) { if (String(e.message).startsWith('robots.txt')) throw e; /* no robots.txt reachable: carry on */ }
  }
  let last;
  for (let i = 0; i <= retries; i++) {
    try {
      const r = await fetch(url, { headers: { 'user-agent': UA, accept: 'text/html,text/plain,*/*' }, signal: AbortSignal.timeout(timeoutMs), redirect: 'follow' });
      if (!r.ok) throw new Error('HTTP ' + r.status);
      return await r.text();
    } catch (e) { last = e; await new Promise((res) => setTimeout(res, 2000 * (i + 1))); }
  }
  throw last;
}

/** HTML to plain text, so parsers do not depend on tag structure. */
export const htmlToText = (html) => html.replace(/<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>/gi, ' ').replace(/<[^>]+>/g, ' ').replace(/&nbsp;|&#160;/g, ' ').replace(/&amp;/g, '&').replace(/&#8377;|&#x20B9;/gi, '₹').replace(/\s+/g, ' ').trim();

/**
 * Store one feed result in live.json.
 * On success: data replaced, fetchedAt = now. On failure: old data kept, ok=false, lastGoodAt remembered.
 * The app shows a yellow "stale since" badge from these fields. Returns a list of change notes.
 */
export function applyFeed(live, key, result, now = new Date().toISOString()) {
  const prev = live.feeds[key] || {};
  if (!result.ok) {
    live.feeds[key] = { ...prev, ok: false, error: String(result.error).slice(0, 300), lastGoodAt: prev.ok === false ? prev.lastGoodAt : prev.fetchedAt, fetchedAt: prev.fetchedAt ?? null, lastTriedAt: now };
    return [];
  }
  const changes = result.diff ? result.diff(prev.data, result.data) : [];
  const next = { ...prev, ...result.meta, ok: true, mode: 'auto', error: undefined, lastGoodAt: undefined, lastTriedAt: now, fetchedAt: now, data: result.data };
  if (result.history) next.history = result.history(prev);
  live.feeds[key] = next;
  return changes;
}

export function addUpdate(live, u) {
  live.updates = live.updates || [];
  if (live.updates.some((x) => x.id === u.id)) return false;
  live.updates.unshift(u);
  live.updates = live.updates.slice(0, 60);
  return true;
}

export async function writeBundle() {
  const facts = await readJson(path.join(DATA, 'facts.json'));
  const live = await readJson(path.join(DATA, 'live.json'));
  await writeFile(path.join(DATA, 'bundle.js'), '// Generated by scripts/bundle.mjs. Do not edit.\nwindow.NP_BUNDLE=' + JSON.stringify({ facts, live }) + ';\n');
}
